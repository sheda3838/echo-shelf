/**
 * Returns the matching icon component for a given content type.
 */
export function getContentTypeIcon(contentType?: string) {
  switch (contentType?.toLowerCase()) {
    case "article":
      return ArticleIcon;
    case "note":
      return NoteIcon;
    case "video":
      return VideoIcon;
    case "repo":
      return RepoIcon;
    case "document":
      return DocumentIcon;
    case "url":
      return UrlIcon;
    case "image":
      return ImageIcon;
    default:
      return GenericItemIcon;
  }
}

/**
 * Returns standardized, cohesive badge styles aligned with Echo Shelf's brand theme.
 */
export function getContentTypeBadgeColor(type?: string): string {
  switch (type?.toLowerCase()) {
    case "article":
    case "url":
      return "bg-teal-50 text-teal-800 dark:bg-teal-950/60 dark:text-teal-300 border-teal-200 dark:border-teal-800/70";
    case "repo":
      return "bg-slate-100 text-slate-800 dark:bg-slate-800/80 dark:text-slate-200 border-slate-200 dark:border-slate-700/60";
    case "video":
      return "bg-emerald-50 text-emerald-800 dark:bg-emerald-950/60 dark:text-emerald-300 border-emerald-200 dark:border-emerald-800/70";
    case "document":
      return "bg-zinc-100 text-zinc-800 dark:bg-zinc-800 dark:text-zinc-200 border-zinc-200 dark:border-zinc-700/60";
    case "image":
      return "bg-emerald-50 text-emerald-900 dark:bg-emerald-950/80 dark:text-emerald-200 border-emerald-300 dark:border-emerald-700/60";
    case "note":
      return "bg-emerald-100/70 text-emerald-900 dark:bg-emerald-900/60 dark:text-emerald-200 border-emerald-300 dark:border-emerald-700/60";
    default:
      return "bg-zinc-100 text-zinc-700 dark:bg-zinc-800 dark:text-zinc-300 border-zinc-200 dark:border-zinc-700/60";
  }
}

export function ContentTypeIcon({
  contentType,
  className = "w-4 h-4",
  ...props
}: {
  contentType?: string;
  className?: string;
} & React.SVGProps<SVGSVGElement>) {
  switch (contentType?.toLowerCase()) {
    case "article":
      return <ArticleIcon className={className} {...props} />;
    case "note":
      return <NoteIcon className={className} {...props} />;
    case "video":
      return <VideoIcon className={className} {...props} />;
    case "repo":
      return <RepoIcon className={className} {...props} />;
    case "document":
      return <DocumentIcon className={className} {...props} />;
    case "url":
      return <UrlIcon className={className} {...props} />;
    case "image":
      return <ImageIcon className={className} {...props} />;
    default:
      return <GenericItemIcon className={className} {...props} />;
  }
}

